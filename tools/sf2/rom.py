#!/usr/bin/env python3
"""Shared ROM access + bank helpers for the SF2 data extractors.

The retail ROM is headerless / 1,048,576 bytes, so file offset == LoROM linear
offset (bank b occupies file b*0x8000 .. b*0x8000+0x7FFF, CPU-addressable at
$b:8000).  All offsets in this package are file offsets, matching
docs/SF2_RECON.md.
"""

from __future__ import annotations

import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROM_PATH = os.path.join(REPO_ROOT, "Star Fox 2 (USA, Europe).sfc")

# Generated Rust module directory (crate: rust/sf2-data) and gitignored data
# output directory (binary blobs; do NOT commit -- treated like data/).
RUST_SRC = os.path.join(REPO_ROOT, "rust", "sf2-data", "src")
DATA_DIR = os.path.join(REPO_ROOT, "data", "sf2")


def load_rom() -> bytes:
    with open(ROM_PATH, "rb") as f:
        return f.read()


def u16(d: bytes, o: int) -> int:
    return d[o] | (d[o + 1] << 8)


def s8(b: int) -> int:
    return b - 256 if b >= 128 else b


def sw16(d: bytes, o: int) -> int:
    v = u16(d, o)
    return v - 65536 if v >= 32768 else v


