#!/usr/bin/env python3
"""Generate the source ShapeHdr-word to flat native shape-id table.

The assembled SF1 path programs embed the low word of relocated ShapeHdr
symbols. The Rust port keeps those programs byte-exact as an input artifact,
but live objects use bounded flat shape ids. This generator joins the checked
assembler symbol file to the compiled native mesh catalog so that conversion
happens at the bytecode boundary rather than leaking source addresses into
gameplay or rendering state.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SHAPE_DATA = ROOT / "rust" / "sf-render" / "src" / "shape_data.rs"
SYMBOLS = ROOT / "reference" / "ultrastarfox" / "SYMBOLS.TXT"
OUTPUT = ROOT / "rust" / "sf-core" / "src" / "sf1_shape_words.rs"
PATH_SOURCES = [
    ROOT / "reference" / "ultrastarfox" / "SF" / "PATH" / "PATHDATA.ASM",
    ROOT / "reference" / "ultrastarfox" / "SF" / "PATH" / "DPATHDAT.ASM",
    ROOT / "reference" / "ultrastarfox" / "SF" / "PATH" / "KPATHDAT.ASM",
]

# Renderer-owned builtins are deliberately installed over compiled source
# meshes, but path comparisons still need their source ShapeHdr words.
BUILTIN_SHAPES = {
    "nullshape": 0,
    "boss_7_0": 421,
    "boss_7_1": 55,
    "boss_7_1o": 422,
    "boss_7_2": 423,
    "boss_7_3": 424,
    "boss_7_4": 425,
}

# Source-only envelope used solely to size a robot explosion. Its ShapeHdr has
# no points or faces, so it intentionally resolves to the null visual shape.
NON_MESH_SHAPES = {"mediumshape"}


def compiled_shapes() -> dict[str, int]:
    text = SHAPE_DATA.read_text()
    pairs = re.findall(
        r"ShapeDataEntry\s*\{.*?shape_id:\s*(\d+),.*?name:\s*\"([^\"]+)\"",
        text,
        re.DOTALL,
    )
    if not pairs:
        raise RuntimeError(f"no shape entries found in {SHAPE_DATA}")
    result = {name.lower(): int(shape_id) for shape_id, name in pairs}
    result.update(BUILTIN_SHAPES)
    return result


def relocated_symbols() -> dict[str, int]:
    result: dict[str, int] = {}
    for raw in SYMBOLS.read_text(encoding="latin1", errors="ignore").splitlines():
        match = re.fullmatch(r"(\S+)\s+\$([0-9A-Fa-f]+)", raw.strip())
        if not match:
            continue
        address = int(match.group(2), 16)
        if address >> 16 == 0:
            result.setdefault(match.group(1).lower(), address)
    return result


def referenced_path_shapes() -> set[str]:
    """Collect every literal ShapeHdr operand in the retail path sources."""
    result: set[str] = set()
    pattern = re.compile(
        r"\b(P_QSPAWN|P_SPAWN|P_DEBRIS|P_FINDSHAPE|P_FINDNEXTSHAPE|"
        r"P_SET|P_IFSAME|P_IFNOTSAME)\b\s*(.*)",
        re.IGNORECASE,
    )
    for path in PATH_SOURCES:
        for raw in path.read_text(encoding="latin1", errors="ignore").splitlines():
            match = pattern.search(raw.split(";", 1)[0])
            if not match:
                continue
            opcode = match.group(1).upper()
            args = [arg.strip().lower() for arg in match.group(2).split(",")]
            name: str | None = None
            if opcode == "P_QSPAWN" and args:
                name = args[0]
            elif opcode == "P_SPAWN" and len(args) >= 7:
                name = args[6]
            elif opcode in {"P_DEBRIS", "P_FINDSHAPE", "P_FINDNEXTSHAPE"} and args:
                name = args[0]
            elif opcode in {"P_SET", "P_IFSAME", "P_IFNOTSAME"} and len(args) >= 2:
                if args[0] == "shape":
                    name = args[1]
            if name and re.fullmatch(r"[a-z_][a-z0-9_]*", name):
                result.add(name)
    return result


def generate() -> str:
    symbols = relocated_symbols()
    shapes = compiled_shapes()
    missing = sorted(referenced_path_shapes() - shapes.keys() - NON_MESH_SHAPES)
    if missing:
        raise RuntimeError(f"retail path shapes lack native meshes: {', '.join(missing)}")
    by_word: dict[int, tuple[int, str]] = {}
    for name, shape_id in shapes.items():
        address = symbols.get(name)
        if address is None:
            continue
        source_word = address & 0xFFFF
        previous = by_word.get(source_word)
        if previous is not None and previous[0] != shape_id:
            raise RuntimeError(
                f"source word 0x{source_word:04X} maps to both "
                f"{previous[1]} ({previous[0]}) and {name} ({shape_id})"
            )
        by_word[source_word] = (shape_id, name)

    rows = "\n".join(
        f"    // {name}\n    (0x{word:04X}, {shape_id}),"
        for word, (shape_id, name) in sorted(by_word.items())
    )
    return f'''// Auto-generated by tools/sf1_shape_word_gen.py -- do not edit.
//! Conversion table for source ShapeHdr words embedded in assembled SF1 data.

pub const SOURCE_SHAPE_WORDS: &[(u16, u16)] = &[
{rows}
];

pub fn flat_id(source_word: u16) -> Option<u16> {{
    SOURCE_SHAPE_WORDS
        .binary_search_by_key(&source_word, |&(word, _)| word)
        .ok()
        .map(|index| SOURCE_SHAPE_WORDS[index].1)
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != generated:
            raise SystemExit(f"{OUTPUT} is stale; run tools/sf1_shape_word_gen.py")
        return
    OUTPUT.write_text(generated)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
