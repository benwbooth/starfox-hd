//! Hand-tuned built-in shape meshes (Arwing + Boss7 parts).
//!
//! Port (C oracle): the static tables in `src/renderer/shapes.c`
//! (`arwing_verts`/`arwing_faces`, `boss7_*_verts`/`_faces` and the boss7
//! per-frame vertex overlays). These override the compiled ASM data in
//! `Shapes_RegisterBuiltins`, exactly like the C.

use crate::shape_data::{ShapeFace, ShapeVertex};

/// `SV(x, y, z)` from shapes.c: Y is negated (Star Fox +Y is screen-down,
/// OpenGL +Y is screen-up).
const fn sv(x: f32, y: f32, z: f32) -> ShapeVertex {
    ShapeVertex { x, y: -y, z }
}

const fn f3(ci: u8, a: u16, b: u16, c: u16) -> ShapeFace {
    ShapeFace {
        vertex_indices: [a, b, c, 0, 0, 0, 0, 0, 0, 0, 0, 0],
        num_verts: 3,
        color_index: ci,
    }
}

const fn f4(ci: u8, a: u16, b: u16, c: u16, d: u16) -> ShapeFace {
    ShapeFace {
        vertex_indices: [a, b, c, d, 0, 0, 0, 0, 0, 0, 0, 0],
        num_verts: 4,
        color_index: ci,
    }
}

const fn f6(ci: u8, a: u16, b: u16, c: u16, d: u16, e: u16, f: u16) -> ShapeFace {
    ShapeFace {
        vertex_indices: [a, b, c, d, e, f, 0, 0, 0, 0, 0, 0],
        num_verts: 6,
        color_index: ci,
    }
}

/// Raw vertex (already in GL convention — the C `arwing_verts` table stores
/// pre-negated Y values).
const fn rv(x: f32, y: f32, z: f32) -> ShapeVertex {
    ShapeVertex { x, y, z }
}

