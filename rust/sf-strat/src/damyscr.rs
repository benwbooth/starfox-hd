pub fn damyscr_init(g: &mut Game, idx: u16) {
    set_object_path(g, idx, PATH_ID_DAMYSCR);

    let choice = (sf_random(&mut g.vars) & SHAPE_CHOICE_INDEX_MASK) as usize / 2;
    g.objs.aliens[idx as usize].shape = DAMYSCR_SHAPES[choice] as u16;

    initialize_path_object(g, idx);
}

fn strategy_id(world: &mut World, strategy: StrategyFn) -> StratId {
    if let Some(index) = world
        .strat_registry
        .iter()
        .position(|&registered| registered as usize == strategy as usize)
    {
        StratId(index as u16)
    } else {
        world.register_strategy(strategy)
    }
}

pub fn register(world: &mut World) {
    let strategy = strategy_id(world, damyscr_init);
    world.register_direct_strategy(STRATEGY_DAMYSCR, strategy);
}
