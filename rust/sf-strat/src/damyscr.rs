use sf_game::game::{Game, StrategyFn};
use sf_game::world::World;
use sf_path::ids::PATH_ID_DAMYSCR;

use crate::common::sf_random;
use crate::path_adapter::{initialize_path_object, set_object_path};

/// Typed native dispatch identity used by Black Hole mother-map entries.
pub const STRATEGY_DAMYSCR: sf_map::consts::DirectStrategy =
    sf_map::consts::DirectStrategy::Damyscr;

const SHAPE_CHOICE_INDEX_MASK: u16 = 62;

