//! Scripted-input trace parity for the sf-strat player lane against the C
//! oracle.
//!
//! NOTE: the fixture intentionally DIVERGES from the frozen C oracle in eleven
//! places that fix player-facing bugs present in the C port:
//!   * barrel roll now triggers on the L/R shoulder buttons only (the C port
//!     wrongly also rolled on dpad LEFT/RIGHT steering), so the flight scenario
//!     no longer rolls at the LEFT/RIGHT press ticks;
//!   * player laser/beam bolts spawn with a visible shape (11) instead of the
//!     C stub's shape 0 + ASF_INVISIBLE, so laser objects read `slot:11:...`.
//!   * the bridge-clear duplicate runs ROM `clshipBridgeboost_Istrat`
//!     (PCSTRATS.ASM:77-83, GCSTRATS.ASM:642-668); the C harness/port left that
//!     duplicated ship inert after spawning it.
//!   * temporary boost sprites apply the signed `boostZoff` through the host's
//!     pitch and yaw (`GSTRATS.ASM:723-731`, `STRATMAC.INC:4098-4189`); the C
//!     port parked them at the host origin and omitted the rotated offset.
//!   * `boostZoff` and camera Y are independent typed fields. A temporary Rust
//!     WRAM-shim address assigned during the port once overlapped the high byte
//!     of camera Y, producing `-7680` when `boostZoff` was `-30`; neither the C
//!     globals nor the original allocation map (`GILESALC.INC`) alias them.
//!   * `playerdead_Istrat` falls through into `playerdead_strat` on the lethal
//!     frame, clears `colldisable`, and starts its 60-count crash immediately
//!     (`PSTRATS.ASM:3104-3142`). The frozen C port deferred the first crash
//!     body and incorrectly kept collision disabled for the whole sequence.
//!   * terminal `pexplode_Istrat` creates the inert player/camera anchor and
//!     large particle, retains `GF_PLAYERDYING`, installs the generic explosion
//!     callbacks on the ship, and removes that ship on the following strategy
//!     pass (`PSTRATS.ASM:3228-3273`). The frozen C port only set the shell's
//!     dead flag and left the ship alive as the sole player object.
//!   * the ordinary lower-screen clamp runs when `pml_Bbottom` is clear; when
//!     set, the detailed body-collision lane owns the floor
//!     (`PSTRATS.ASM:1912-1922`). The deleted C port inverted that condition.
//!   * `playeropening_Istrat` and `viewopening_Istrat` fall through into their
//!     per-frame bodies on the creation frame, and the opening Y-float table's
//!     explicit scale argument doubles each word (`PISTRATS.ASM:46-97`,
//!     `GISTRATS.ASM:617-683`). The frozen C port deferred both bodies and
//!     omitted the table scale.
//!   * `viewopening_strat` state zero falls through into state one on its
//!     transition frame, retaining the already-offset scratch targets and
//!     decrementing the new timer immediately (`GISTRATS.ASM:648-668`). The
//!     frozen C port returned after changing state. Retail/native semantic
//!     coexecution certifies the corrected camera positions.
//!   * `viewopening_strat` takes its zoom branch only when the X chase began
//!     at its target. The source `s_achase_alvar` carry is decided before the
//!     chase, while the frozen C/Rust trace switched on the frame X first
//!     reached the target (`STRATMAC.INC:525-549`, `GISTRATS.ASM:665-671`).
//!   * `boost_Istrat` falls through into `boost_strat`, so a new flame is
//!     attached and consumes its first lifetime tick on its creation frame
//!     (`GSTRATS.ASM:715-731`). The frozen C/Rust trace deferred that work.
//!     The new flame and opening camera also retain source `s_make_obj` list
//!     order after their host, preserving same-pass flag and attachment timing.
//!   * `init_strats_l` advances the four-byte runtime random stream once per
//!     logic frame before object strategies run (`GSTRATS.ASM:633`). The
//!     frozen C harness omitted this shared game-loop draw.
//!   * `floatCLship_l` doubles the view-float table word before applying each
//!     launch wingman's vertical offset (`GCSTRATS.ASM:2069-2085`). The frozen
//!     C port used the unscaled word.
//! Re-baseline with `SF_BLESS_SP_PLAYER=<abs fixture path>` (see the test body).
//!
//! Fixture: `tests/fixtures/sp_player_trace.txt`, generated by a scratchpad
//! harness (`sp_harness/sp_player_trace.c`) compiling the real
//! `strat_player.c` + `strat_common.c` + `obj.c` + `game_vars.c` with pad/
//! RNG/sound stubs. Six scenarios:
//!   1. flight  — playermove/boost/brake/fire/barrel-roll, scripted body
//!      hit at t=150 and lethal hit at t=165 (hitflash RNG, death chain,
//!      lives decrement)
//!   2. opening — playeropening_Istrat + viewopening camera chain
//!   3. exitbase — hangar wait/Go/Follow launch + friendstart3 wingman
//!   4. nucleus — playerEscapeNucleus chain
//!   5. bridge  — playerclearbridge chain (incl. dupplayer + resumed fire)
//!   6. shipintro — MAP1_1A flyby object
//! Every tick both sides dump the player alien, the shared globals, every
//! active alien (slot order) and the sounds triggered; the texts must be
//! byte-identical.
//!
//! Regenerate (from the repo root, harness sources in the session
//! scratchpad `sp_harness/`):
//!   gcc -O2 -Isrc -o sp_player_trace sp_player_trace.c \
//!       src/strat/strat_player.c src/strat/strat_common.c \
//!       src/game/obj.c src/game/game_vars.c sp_stubs.c -lm && \
//!   ./sp_player_trace && cp sp_player_trace.txt \
//!       rust/sf-strat/tests/fixtures/

