pub(super) fn actions(retail_frame: u16, actor: usize) -> &'static [InterceptionMissileAction] {
    let Some(offset) = retail_frame.checked_sub(START_RETAIL_FRAME) else {
        return &[];
    };
    if offset % RETAIL_FRAME_STEP != 0 {
        return &[];
    }
    let Some(ranges) = TICKS.get(usize::from(offset / RETAIL_FRAME_STEP)) else {
        return &[];
    };
    let Some(range) = ranges.get(actor) else {
        return &[];
    };
    &ACTIONS[usize::from(range.start)..usize::from(range.start) + usize::from(range.len)]
}
