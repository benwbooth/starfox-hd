#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct ActionRange {
    start: u16,
    len: u8,
}

impl ActionRange {
    const fn new(start: u16, len: u8) -> Self {
        Self { start, len }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct ActionRangePair {
    upper: ActionRange,
    lower: ActionRange,
}

